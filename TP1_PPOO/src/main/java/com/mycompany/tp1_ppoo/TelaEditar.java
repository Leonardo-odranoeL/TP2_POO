    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // 1. Pega as novas informações escolhidas pelo usuário
        String categoria = cmbCategoria.getSelectedItem().toString();
        String status = chkAtivo.isSelected() ? "Ativo" : "Inativo";
        String nome = txtNome.getText(); // O nome está bloqueado, servirá como referência

        // 2. Comando SQL para ATUALIZAR (UPDATE) em vez de INSERIR
        String sql = "UPDATE tb_Funcionarios SET Categoria = ?, Status = ? WHERE Nome = ?";
    
        try(Connection conn = Conexao.conectar()){
            PreparedStatement mensagem = conn.prepareStatement(sql);
            mensagem.setString(1, categoria);
            mensagem.setString(2, status);
            mensagem.setString(3, nome); // O 'WHERE Nome = ?' usa esse parâmetro para achar o registro certo
        
            mensagem.executeUpdate();   
        
            javax.swing.JOptionPane.showMessageDialog(this, "Registro atualizado com sucesso!");
            this.dispose(); // Fecha a tela de edição
        
        } catch(SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao atualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

