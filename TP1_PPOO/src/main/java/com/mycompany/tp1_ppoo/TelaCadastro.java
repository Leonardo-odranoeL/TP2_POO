    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        // 1. Pega os dados digitados
        String nome = txtNome.getText();
        String categoria = cmbCategoria.getSelectedItem().toString();
        String status = chkAtivo.isSelected() ? "Ativo" : "Inativo";

        String sql = "INSERT INTO tb_Funcionarios (Nome, Categoria, Status) VALUES (?, ?, ?)";
        
        try(Connection conn = Conexao.conectar()){
            PreparedStatement mensagem = conn.prepareStatement(sql);
            mensagem.setString(1, nome);
            mensagem.setString(2, categoria);
            mensagem.setString(3, status);  
            mensagem.executeUpdate();           
        } catch(SQLException e) {
                throw new RuntimeException("Erro ao conectar! ", e);
                }
    
        // 3. Mostra mensagem de sucesso (opcional)
        javax.swing.JOptionPane.showMessageDialog(this, "Salvo com sucesso!");
    
        // 4. FECHA apenas a tela de cadastro. 
        // Como a Tela Principal nunca foi fechada, ela vai aparecer naturalmente atrás dessa!
        this.dispose();
    }//GEN-LAST:event_btnSalvarActionPerformed

